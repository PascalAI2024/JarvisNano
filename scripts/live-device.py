def command_evidence(args: argparse.Namespace) -> int:
    """Capture a timestamped, machine-readable device evidence bundle."""
    dev = Device(args.host, args.timeout)
    output_dir = args.output or os.path.join(REPORT_DIR, f"{now_slug()}-evidence")
    os.makedirs(output_dir, exist_ok=True)
    manifest: dict[str, Any] = {
        "schema": "jarvis-live-evidence/v1",
        "captured_at": dt.datetime.now().astimezone().isoformat(timespec="seconds"),
        "device": dev.base,
        "proof_scope": PROOF_SCOPE,
        "physical_proof": {
            "status": "not_established_by_cli",
            "required": [
                "person or camera observes the requested pattern on the AMOLED",
                "person completes touch targets on the physical glass",
                "person or calibrated microphone confirms speaker output",
            ],
        },
        "artifacts": {},
    }
    successes = 0

    # Broad status stays useful across old and new firmware. Individual 404s
    # are evidence of route availability, not a reason to abandon the bundle.
    status = collect_snapshot(dev, args.tail)
    write_json(os.path.join(output_dir, "runtime-status.json"), status)
    manifest["artifacts"]["runtime_status"] = "runtime-status.json"
    successes += sum(
        1 for result in status.get("endpoints", {}).values()
        if result.get("http") == 200
    )

    display_info = capture_display_info(dev)
    write_json(os.path.join(output_dir, "display-snapshot-info.json"), display_info)
    manifest["display"] = {"info": display_info}
    successes += 1 if display_info.get("http") == 200 else 0

    if args.pattern:
        pattern_path = "/api/display/test?" + urllib.parse.urlencode({"pattern": args.pattern})
        try:
            code, raw, body = dev.request("POST", pattern_path)
            pattern_result = {
                "http": code,
                "body": body,
                "raw": raw[:4000],
                "proof": PROOF_SCOPE["display_test_command"],
            }
            print_route_result("/api/display/test", code, body)
            successes += 1 if 200 <= code < 300 else 0
            manifest["display"]["test_pattern"] = pattern_result
            if 200 <= code < 300 and args.pattern_wait > 0:
                print_check("WAIT", "panel pattern observation window", f"{args.pattern_wait:.1f}s")
                time.sleep(args.pattern_wait)
        except Exception as exc:  # noqa: BLE001
            manifest["display"]["test_pattern"] = {"error": str(exc)}
            print_check("N/A", "/api/display/test", str(exc))

    display_capture = capture_display_ppm(dev, output_dir, "display-snapshot")
    manifest["display"]["snapshot"] = display_capture
    successes += 1 if display_capture.get("http") == 200 and "path" in display_capture else 0

    if args.pattern and not args.leave_pattern and args.pattern != "off":
        try:
            code, _, body = dev.request("POST", "/api/display/test?pattern=off")
            manifest["display"]["restore"] = {"http": code, "body": body}
            print_route_result("/api/display/test?pattern=off", code, body)
        except Exception as exc:  # noqa: BLE001
            manifest["display"]["restore"] = {"error": str(exc)}
            print_check("WARN", "display pattern restore", str(exc))

    if args.audio_self_test:
        manifest["audio_self_test"] = start_audio_self_test(dev)
        successes += 1 if manifest["audio_self_test"].get("ok") else 0
        if manifest["audio_self_test"].get("ok") and args.audio_wait > 0:
            print_check("WAIT", "audio diagnostic capture", "queued diagnostic + graceful voice drain")
            wait_audio_self_test_complete(dev, args.audio_wait + 6.0)

    audio_metrics = capture_audio_metrics(dev, output_dir)
    audio_taps = download_audio_taps(dev, output_dir, args.source)
    manifest["audio"] = {"metrics": audio_metrics, "taps": audio_taps}
    successes += 1 if audio_metrics.get("http") == 200 else 0
    successes += sum(
        1 for result in audio_taps.values()
        if result.get("http") == 200 and "wav" in result
    )

    physical_template = {
        "recorded_at": None,
        "observer": None,
        "display_pattern_observed": None,
        "display_matches_software_mirror": None,
        "touch_target_rounds_passed": None,
        "speaker_chirp_audible": None,
        "notes": "Fill this from a person/camera observation; the CLI intentionally cannot.",
    }
    write_json(os.path.join(output_dir, "physical-observation-template.json"), physical_template)
    manifest["artifacts"]["physical_observation_template"] = "physical-observation-template.json"

    # Write last so the manifest describes even partial captures and failures.
    write_json(os.path.join(output_dir, "manifest.json"), manifest)
    print_check("OK", "evidence bundle written", output_dir)
    print_check(
        "PROOF",
        "bundle boundary",
        "software/control/electrical evidence captured; physical observations remain explicit blanks",
    )
    if successes == 0:
        print_check("WARN", "no diagnostic route succeeded", "bundle records route/transport failures")
        return 1
    return 0


def command_restart(args: argparse.Namespace) -> int:
    dev = Device(args.host, args.timeout)
    before_uptime = None
    try:
        _, _, health = dev.get("/api/health")
        if isinstance(health, dict):
            before_uptime = health.get("uptime_ms")
    except Exception:
        pass

    code, _, body = dev.post("/api/restart", {})
    print_check("OK" if 200 <= code < 300 else "FAIL", f"POST /api/restart http={code}", short_json(body))
    if not (200 <= code < 300):
        return 1

    saw_down = False
    deadline = time.time() + args.wait
    while time.time() < deadline:
        time.sleep(args.interval)
        try:
            code, _, body = dev.get("/api/health")
            if code == 200 and isinstance(body, dict):
                uptime = body.get("uptime_ms")
                if saw_down or before_uptime is None or (isinstance(uptime, (int, float)) and uptime < before_uptime):
                    print_check("OK", "device back online", short_json(body))
                    return 0
                print_check("WAIT", "device still online", f"uptime_ms={uptime}")
            else:
                saw_down = True
                print_check("WAIT", f"health http={code}", short_json(body))
        except Exception as exc:  # noqa: BLE001
            saw_down = True
            print_check("WAIT", "device down", str(exc)[:160])
    print_check("FAIL", "device did not return after restart", f"timeout={args.wait}s")
    return 1


