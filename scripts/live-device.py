def download_audio_taps(dev: Device, output_dir: str,
                        sources: tuple[str, ...] | list[str]) -> dict[str, Any]:
    os.makedirs(output_dir, exist_ok=True)
    results: dict[str, Any] = {}
    for source in sources:
        path = "/api/audio/tap.wav?" + urllib.parse.urlencode({"source": source})
        try:
            code, headers, data = dev.get_bytes(path)
        except Exception as exc:  # noqa: BLE001
            print_check("N/A", f"audio tap {source}", str(exc))
            results[source] = {"error": str(exc)}
            continue

        if source == "playback":
            proof = PROOF_SCOPE["audio_playback_tap"]
        elif source == "reference":
            proof = PROOF_SCOPE["audio_reference_tap"]
        else:
            proof = PROOF_SCOPE["audio_mic_tap"]
        result: dict[str, Any] = {
            "http": code,
            "headers": headers,
            "bytes": len(data),
            "sha256": sha256_hex(data),
            "proof": proof,
        }
        results[source] = result
        if code != 200:
            result["body"] = data.decode("utf-8", errors="replace")[:1000]
            print_route_result(f"audio tap {source}", code, result["body"])
            continue

        info = wav_info(data)
        if info is None:
            result["error"] = "HTTP 200 body is not canonical PCM WAV"
            print_check("FAIL", f"audio tap {source}", result["error"])
            continue
        wav_path = os.path.join(output_dir, f"audio-{source}.wav")
        write_bytes(wav_path, data)
        result.update({"path": wav_path, "wav": info})
        firmware_level = header_value(headers, "X-Jarvis-Evidence-Level", "unknown")
        result["firmware_evidence_level"] = firmware_level
        print_check(
            "OK",
            f"audio tap {source}",
            f"{wav_path} {info['sample_rate_hz']}Hz {info['duration_ms']}ms firmware_level={firmware_level}",
        )
        print_check("PROOF", f"audio tap {source}", proof["level"] + "; " + proof["does_not_prove"])
    return results


