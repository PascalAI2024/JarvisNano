def start_audio_self_test(dev: Device) -> dict[str, Any]:
    path = "/api/audio/self-test"
    attempts: list[dict[str, Any]] = []
    # Current firmware uses explicit POST intent; GET remains a compatibility
    # fallback for older bench images.
    for method in ("POST", "GET"):
        try:
            code, raw, body = dev.request(method, path)
        except Exception as exc:  # noqa: BLE001
            attempts.append({"method": method, "error": str(exc)})
            continue
        attempts.append({"method": method, "http": code, "body": body, "raw": raw[:4000]})
        if 200 <= code < 300:
            print_check("OK", f"{method} {path} http={code}", short_json(body))
            print_check(
                "PROOF",
                "audio self-test",
                "bounded diagnostic accepted; inspect tap metrics/WAVs for path evidence",
            )
            return {"ok": True, "method": method, "http": code, "body": body, "attempts": attempts,
                    "proof": PROOF_SCOPE["audio_self_test"]}
        if not route_unavailable(code):
            print_check("FAIL", f"{method} {path} http={code}", short_json(body))
            return {"ok": False, "method": method, "http": code, "body": body, "attempts": attempts,
                    "proof": PROOF_SCOPE["audio_self_test"]}
    detail = "route is not present in this firmware"
    if attempts and all("error" in attempt for attempt in attempts):
        detail = "; ".join(str(attempt["error"]) for attempt in attempts)
    print_check("N/A", path, detail)
    return {"ok": False, "unavailable": True, "attempts": attempts,
            "proof": PROOF_SCOPE["audio_self_test"]}


def wait_audio_self_test_complete(dev: Device, timeout: float) -> bool:
    """Wait for the queued test to actually start and finish.

    Always-ready voice may need a graceful drain before the diagnostic owns the
    codec, so sleeping from HTTP acceptance can download a truncated capture.
    """
    deadline = time.monotonic() + max(timeout, 4.0)
    observed = False
    while time.monotonic() < deadline:
        try:
            code, _, body = dev.get("/api/gemini/live")
        except Exception:  # noqa: BLE001 - caller still has a bounded fallback.
            time.sleep(0.15)
            continue
        if code == 200 and isinstance(body, dict):
            queued = bool(body.get("audio_diag_queued"))
            running = bool(body.get("audio_diag_running"))
            observed = observed or queued or running
            if observed and not queued and not running:
                print_check("OK", "audio capture window", "diagnostic completed")
                return True
        time.sleep(0.15)
    print_check("WARN", "audio capture window", "completion was not observed before timeout")
    return False


