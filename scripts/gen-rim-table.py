#!/usr/bin/env python3
"""Generate components/jr_display/src/hud_rim_table.inc: the coverage of the rim ring.

The rim is one hairline ring of a fixed radius (RIM_R in hud_render.c), so the
columns a row crosses and the anti-aliased coverage of each one never change.
They used to be worked out for every painted pixel of every frame; this prints
them once. Row j is the row whose doubled offset from the centre is 2j+1 (rows
above and below the centre are mirror images, and so are the two sides of a
row); a pixel is the column k from the centre column.

The arithmetic is the C arithmetic of the loop it replaces (ring_cols and
ring_dist in hud_render.c), in 32-bit integers with an arithmetic shift.
Change RIM_R or RIM_HW_Q8 there and run this script; test_hud_render.c pins the
table against the formula and fails if the two have drifted apart.

usage: scripts/gen-rim-table.py [--check]   (--check exits 1 if the file is stale)
"""
import math
import sys
from pathlib import Path

RIM_R = 218
RIM_HW_Q8 = 256
# (name, R px, half width Q8, margin in half pixels): the rim, and the rings of the JARVIS dial
# (JD_SUN_R in hud_render.c is the day's arc; its wedge is applied per pixel at run time).
RINGS = [("rim", 218, 256, 3), ("jd184", 184, 192, 4), ("jd131", 131, 160, 4),
         ("jd61", 61, 160, 4), ("jd206", 206, 256, 4)]

OUT = Path(__file__).resolve().parent.parent / "components/jr_display/src/hud_rim_table.inc"


def rows(R, hw, margin):
    r_out_h = 2 * R + margin
    r_in_h = 2 * R - margin
    r4 = 4 * R * R
    inv = (32 << 16) // R
    out = []
    for ady in range(1, r_out_h, 2):
        xo = math.isqrt(r_out_h * r_out_h - ady * ady)
        xi = 0 if ady >= r_in_h else math.isqrt(r_in_h * r_in_h - ady * ady)
        k_hi = (xo - 1) >> 1
        k_lo = (xi - 1) >> 1 if xi > 1 else 0
        cov = []
        if k_hi >= k_lo:
            for k in range(k_lo, k_hi + 1):
                dx2 = 2 * k + 1
                v = (dx2 * dx2 + ady * ady - r4) * inv
                assert -(1 << 31) <= v < (1 << 31)
                dist = v >> 16
                c = hw + 128 - abs(dist)
                cov.append(0 if c <= 0 else min(c, 256))
        # trim the columns that carry no ink at either end
        lo = 0
        while lo < len(cov) and cov[lo] == 0:
            lo += 1
        hi = len(cov)
        while hi > lo and cov[hi - 1] == 0:
            hi -= 1
        cov = cov[lo:hi]
        out.append((k_lo + lo, cov))
    return out


def render():
    lines = ["/* GENERATED by scripts/gen-rim-table.py: do not edit. The per-row columns and coverage of the",
             " * rim ring and of the JARVIS dial's rings: each ring has one radius and one width, so none of",
             " * it changes from frame to frame. Row j is the row whose doubled offset from the centre is 2j+1;",
             " * coverage is stored minus one (1..256 as 0..255). */",
             "typedef struct { uint16_t off; uint8_t k0; uint8_t n; } ring_ent_t;",
             "typedef struct { int rows; const ring_ent_t *ent; const uint8_t *cov; } ring_tab_t;"]
    for name, R, hw, margin in RINGS:
        rs = rows(R, hw, margin)
        flat, heads = [], []
        for k0, cov in rs:
            heads.append((len(flat), k0, len(cov)))
            flat.extend(c - 1 for c in cov)
        assert all(0 <= v <= 255 for v in flat) and len(flat) < 65536
        assert all(h[1] < 256 and h[2] < 256 for h in heads)
        N = name.upper()
        lines.append("#define %s_TABLE_R      %d" % (N, R))
        lines.append("#define %s_TABLE_HW_Q8  %d" % (N, hw))
        lines.append("#define %s_TABLE_ROWS   %d" % (N, len(heads)))
        lines.append("static const ring_ent_t k_%s_rows[%d] = {" % (name, len(heads)))
        for i in range(0, len(heads), 6):
            lines.append("    " + " ".join("{%d,%d,%d}," % h for h in heads[i:i + 6]))
        lines.append("};")
        lines.append("static const uint8_t k_%s_cov[%d] = {" % (name, len(flat)))
        for i in range(0, len(flat), 24):
            lines.append("    " + ",".join(str(v) for v in flat[i:i + 24]) + ",")
        lines.append("};")
        lines.append("static const ring_tab_t k_%s_tab = { %d, k_%s_rows, k_%s_cov };" %
                     (name, len(heads), name, name))
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text, newline="\n")
    print("wrote", OUT, len(text), "bytes of source")
