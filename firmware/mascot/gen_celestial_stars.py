#!/usr/bin/env python3
"""Pick the stars of the CELESTIAL dial that twinkle, and write them as a table.

The celestial dial (dial_celestial.eaf, gen_watch_dials.py) is a baked star
field. A handful of its brightest stars get a slow live glint drawn under the
hands (hud_render.c, hud_celestial_twinkle). Which stars is decided here, at
bake time, from the baked frame itself (dial_celestial_preview.png is the
dial as the device decodes it), so every table row is a star that is really
on the dial:

  * candidates are near-white local maxima (the constellation lines, the hour
    studs and the minute track are gold; the four-point constellation stars
    sit on gold lines): anything within 8 px of gold is dropped, which keeps
    the constellation joints and the studs out;
  * the centre hole (r < 30, where the hand hub sits) and the minute track
    (r > 186) are out of bounds;
  * a star's weight is the light in its 7x7 blob above the local background,
    so a saturated plateau is one star, not forty maxima;
  * the brightest COUNT, at least MIN_SEP px apart.

Each row: x, y, period index (2.0 .. 5.0 s, every period divides 60 s so the
sweep through the minute never jumps), phase (Q16 turns) and strength 0..255.
The assignment of period and phase is a fixed integer recipe, so the file is
reproducible.

Usage:
  python3 gen_celestial_stars.py                 # write the header
  python3 gen_celestial_stars.py --check         # exit 1 if it is stale
  python3 gen_celestial_stars.py --overlay OUT.png   # circle the picked stars

Requires Pillow, numpy, scipy. No network.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw
from scipy import ndimage as ndi

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
PREVIEW = HERE / "reactive" / "dial_celestial_preview.png"
OUT = REPO / "components" / "jr_display" / "src" / "celestial_stars_data.h"

COUNT = 32
MIN_SEP = 16
R_MIN, R_MAX = 30, 186
PERIODS_MS = (2000, 2400, 2500, 3000, 3750, 4000, 5000)   # all divide 60000
CX = CY = 233


def pick() -> list[tuple[int, int, int]]:
    """[(x, y, weight)] brightest first."""
    im = np.asarray(Image.open(PREVIEW).convert("RGBA")).astype(int)
    rgb = im[:, :, :3]
    lum = rgb.max(axis=2)
    gold = (rgb[:, :, 0] - rgb[:, :, 2] > 45) & (rgb[:, :, 0] > 120)
    near_gold = ndi.binary_dilation(gold, iterations=8)
    yy, xx = np.mgrid[0:lum.shape[0], 0:lum.shape[1]]
    rr = np.hypot(xx - CX, yy - CY)
    white = (lum > 150) & ~gold
    bg = ndi.uniform_filter(lum.astype(float), size=15)
    # blob weight: light above the local background in a 7x7 window
    excess = np.clip(lum - bg, 0, None) * white
    weight = ndi.uniform_filter(excess, size=7) * 49
    peak = ndi.maximum_filter(weight, size=9)
    cand = (weight == peak) & (weight > 0) & ~near_gold & (rr > R_MIN) & (rr < R_MAX)
    ys, xs = np.where(cand)
    rows = sorted(((float(weight[y, x]), int(x), int(y)) for y, x in zip(ys, xs)),
                  reverse=True)
    chosen: list[tuple[int, int, int]] = []
    for w, x, y in rows:
        if all((x - cx) ** 2 + (y - cy) ** 2 >= MIN_SEP ** 2 for cx, cy, _ in chosen):
            chosen.append((x, y, int(w)))
        if len(chosen) == COUNT:
            break
    return chosen


def render(stars: list[tuple[int, int, int]]) -> str:
    wmax = max(w for _, _, w in stars)
    lines = []
    seed = 0x9E3779B1
    for i, (x, y, w) in enumerate(stars):
        seed = (seed * 1664525 + 1013904223) & 0xFFFFFFFF
        period = PERIODS_MS[(seed >> 24) % len(PERIODS_MS)]
        phase = (seed >> 8) & 0xFFFF
        strength = 128 + (127 * w) // wmax            # the brightest glint hardest
        lines.append(f"    {{ {x:3d}, {y:3d}, {period:4d}, 0x{phase:04X}, {strength:3d} }},")
    body = "\n".join(lines)
    return f"""/* GENERATED by firmware/mascot/gen_celestial_stars.py. Do not edit.
 * `python3 firmware/mascot/gen_celestial_stars.py --check` fails if stale.
 * The {len(stars)} stars of the CELESTIAL dial that twinkle, in 466-px dial
 * pixels: x, y, period in ms (every one divides 60000), phase in Q16 turns,
 * strength 0..255. Included by hud_render.c only. */
#ifndef JR_DISPLAY_CELESTIAL_STARS_DATA_H
#define JR_DISPLAY_CELESTIAL_STARS_DATA_H

#include <stdint.h>

typedef struct {{
    uint16_t x, y, period_ms, phase_q16;
    uint8_t  strength;
}} hud_star_t;

#define HUD_STAR_COUNT {len(stars)}

static const hud_star_t s_stars[HUD_STAR_COUNT] = {{
{body}
}};

#endif
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--overlay", type=Path)
    args = ap.parse_args()
    stars = pick()
    if len(stars) < 24:
        raise SystemExit(f"celestial stars: only {len(stars)} found, want 24-40")
    text = render(stars)
    print(f"{len(stars)} stars, weights {stars[0][2]} .. {stars[-1][2]}")
    if args.overlay:
        im = Image.open(PREVIEW).convert("RGBA")
        bg = Image.new("RGBA", im.size, (0, 0, 0, 255))
        bg.alpha_composite(im)
        d = ImageDraw.Draw(bg)
        for x, y, _ in stars:
            d.ellipse((x - 6, y - 6, x + 6, y + 6), outline=(255, 60, 60, 255))
        bg.convert("RGB").save(args.overlay)
    if args.check:
        if not OUT.exists() or OUT.read_bytes().replace(b"\r\n", b"\n") != text.encode():
            print("STALE: celestial_stars_data.h")
            return 1
        print("celestial star table is current")
        return 0
    OUT.write_bytes(text.encode())
    return 0


if __name__ == "__main__":
    sys.exit(main())
